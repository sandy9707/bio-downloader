'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const crypto = require('node:crypto');
const {transferRoute, pinSelectedFile, bioSource} = require('../src/main/bio-transfer-guard');
const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'biodl-selected-'));
process.env.BIODL_DATA_DIR = path.join(temp, 'profile');
const main = require('../main');
const axios = require('axios');
const url = 'https://ftp.sra.ebi.ac.uk/vol1/fastq/SRR123/reads.fq.gz';
const selected = {name:'reads.fq.gz', url, transport:'https', sourceSelection:'manual', networkMode:'accelerated'};
(async () => {
  assert.equal(transferRoute(selected, true).guardedUrl, url);
  assert.equal(bioSource(url), url.replace('https:', 'http:'));
  assert.throws(() => transferRoute(selected, false), /加速器/);
  assert.throws(() => transferRoute({...selected,transport:'ftp'}, true), /重新选择/);
  const ftp = {...selected, transport:'ftp', url:url.replace('https:', 'ftp:')};
  assert.throws(() => transferRoute(ftp,true), /明确选择直连/);
  assert.equal(transferRoute({...ftp,networkMode:'direct'},false).guardedUrl,null);
  const destination = path.join(temp,'protected');
  fs.writeFileSync(destination, 'original');
  const raw = JSON.stringify({version:1, engine:'aria2', sourceKey:crypto.createHash('sha256').update(bioSource(url)).digest('hex')});
  fs.writeFileSync(destination + '.biodl.json',raw);
  await assert.rejects(pinSelectedFile(destination,ftp.url,'aria2'), /原文件已保留/);
  assert.equal(fs.readFileSync(destination,'utf8'),'original');
  assert.equal(fs.readFileSync(destination+'.biodl.json','utf8'),raw);
  const clean = path.join(temp,'fresh');
  await pinSelectedFile(clean,ftp.url,'aria2');
  await pinSelectedFile(clean,ftp.url,'aria2');
  await assert.rejects(pinSelectedFile(clean,ftp.url+'2','aria2'), /原文件已保留/);
  const events = [], charges = [];
  main.eventBus.on('download-status', data => events.push(data));
  axios.post = async (...args) => { charges.push(args); return {data:{success:true}}; };
  await main.callIpcHandler('start-download',{files:[{...selected,originalIndex:900},{...ftp,originalIndex:901}],targetDir:temp,token:'fixture',maxConcurrent:1});
  assert.deepEqual(events.filter(e=>e.status==='failed').map(e=>e.index),[900,901]);
  assert.ok(events.every(e=>!['connecting','verifying'].includes(e.phase)));
  assert.equal(charges.length,0);
  assert.equal(fs.existsSync(path.join(temp,selected.name)),false);
  console.log('SELECTED_TRANSFER_OK');
})().catch(error => { console.error(error);process.exitCode=1; }).finally(()=>{ if (path.dirname(temp) === os.tmpdir() && path.basename(temp).startsWith('biodl-selected-')) fs.rmSync(temp,{recursive:true,force:true}); });
