'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync(require('node:path').join(__dirname, '..', 'renderer.js'), 'utf8');
const start = source.indexOf('let currentRealNodeCount = 0;');
const end = source.indexOf('window.optimizeConnections = optimizeConnections;', start);
assert(start > 0 && end > start);
const elements = new Map(['btnOptimizeConnText','btnOptimizeConn','clashValidationProgress','clashValidationProgressFill'].map(id => [id, {style:{},innerText:'',disabled:false,title:''}]));
const notices = [];
let reply = {success:true,nodeCount:7,nodeTier:2,physicalNodeCount:4};
const context = vm.createContext({document:{getElementById:id=>elements.get(id)}, window:{api:{optimizeClash:async()=>reply}},currentUser:{token:'synthetic'},showToast:(...args)=>notices.push(args),switchTab:()=>{},setTimeout:()=>0});
vm.runInContext(source.slice(start,end),context);
(async()=>{
  vm.runInContext('updateNodeCountUI(7,2,4)',context);
  assert.match(elements.get('btnOptimizeConnText').innerText,/4.*线路/,'show measured route groups, not account aliases as routes');
  vm.runInContext('updateNodeCountUI(0,null,0)',context);
  assert.doesNotMatch(elements.get('btnOptimizeConnText').innerText,/7|二级/,'zero and null must clear stale success');
  vm.runInContext('setClashValidationProgress({phase:"sampling",completed:2,total:8,verified:false})',context);
  assert.match(elements.get('btnOptimizeConnText').innerText,/2 \/ 8/);
  vm.runInContext('setClashValidationProgress({phase:"selection",continuedToTier2:true,verified:false})',context);
  assert.match(elements.get('btnOptimizeConnText').innerText,/不足 5/);
  await vm.runInContext('optimizeConnections()',context);
  assert.match(notices.at(-1)[0],/4.*线路/);
  reply={success:false,message:'配置加载失败',nodeCount:0,nodeTier:null,physicalNodeCount:0};
  await vm.runInContext('optimizeConnections()',context);
  assert.equal(notices.at(-1)[1],'error');
  assert.doesNotMatch(elements.get('btnOptimizeConnText').innerText,/二级|7/);
  assert.equal(elements.get('btnOptimizeConn').disabled,false);
  console.log('NODE_STATUS_UI_OK route count, zero reset, explicit failure');
})().catch(error=>{console.error(error);process.exitCode=1;});
